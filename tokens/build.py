#!/usr/bin/env python3
"""Build the chilichip design tokens.

Reads tokens/tokens.json and writes:

  docs/tokens/chilichip.css   CSS custom properties (dark by default, light opt-in)
  docs/tokens/chilichip.json  every token with colours resolved to hex
  docs/tokens/chilichip.hpp   C++ header with the colours for the console
  docs/assets/chilichip-logo.svg  copy of the logo for the docs
  tokens/snippets/*.md        tables and swatches the docs include

Run: python3 tokens/build.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "tokens" / "tokens.json"
OUT = ROOT / "docs" / "tokens"
SNIPPETS = ROOT / "tokens" / "snippets"
NOTE = "Generated by tokens/build.py from tokens/tokens.json. Do not edit."

# Groups that become plain CSS variables: --cc-<group>-<name>
SCALES = ("font", "text", "leading", "tracking", "space", "radius", "cut", "shadow", "motion")
SOURCES = {
    "logo": "From the logo",
    "derived": "Derived from the logo",
    "support": "Support",
    "neutral": "Neutrals",
}
TEXT_ROLES = ("text", "muted", "accent-text", "link", "success", "warning", "danger")


def load():
    return json.loads(SOURCE.read_text())


def rgb(hex_colour):
    h = hex_colour.lstrip("#")
    return tuple(int(h[i : i + 2], 16) for i in (0, 2, 4))


def rgb565(hex_colour):
    r, g, b = rgb(hex_colour)
    return (r >> 3) << 11 | (g >> 2) << 5 | b >> 3


def luminance(hex_colour):
    channels = [c / 255 for c in rgb(hex_colour)]
    linear = [c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4 for c in channels]
    return 0.2126 * linear[0] + 0.7152 * linear[1] + 0.0722 * linear[2]


def contrast(a, b):
    """WCAG contrast ratio between two colours, rounded to 2 places."""
    hi, lo = sorted((luminance(a), luminance(b)), reverse=True)
    return round((hi + 0.05) / (lo + 0.05), 2)


def resolved(tokens, theme):
    return {role: tokens["color"][name]["value"] for role, name in tokens["theme"][theme].items()}


def css(tokens):
    def block(selector, lines):
        return selector + " {\n" + "\n".join(f"  {line}" for line in lines) + "\n}\n"

    def roles(theme):
        return [f"--cc-{role}: var(--cc-{name});" for role, name in tokens["theme"][theme].items()]

    base = ["/* Colours */"]
    base += [f"--cc-{name}: {c['value']};" for name, c in tokens["color"].items()]
    base += ["", "/* Roles, dark theme (the default) */"] + roles("dark")
    for group in SCALES:
        base += ["", f"/* {group.capitalize()} */"]
        base += [f"--cc-{group}-{name}: {value};" for name, value in tokens[group].items()]
    return "\n".join(
        [
            f"/* chilichip design tokens. {NOTE} */",
            block(":root", base),
            "/* Light theme: set data-theme=\"light\" on <html> or any container */",
            block('[data-theme="light"]', roles("light")),
        ]
    )


def flat_json(tokens):
    data = {"color": {name: c["value"] for name, c in tokens["color"].items()}}
    data["theme"] = {theme: resolved(tokens, theme) for theme in tokens["theme"]}
    data.update({group: tokens[group] for group in SCALES})
    return json.dumps(data, indent=2) + "\n"


def hpp(tokens):
    ident = lambda name: name.replace("-", "_")
    lines = [
        f"// chilichip colours for the console. {NOTE}",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace chilichip {",
        "",
        "struct Rgb {",
        "  std::uint8_t r, g, b;",
        "  // The colour as the display stores it (RGB565).",
        "  constexpr std::uint16_t rgb565() const {",
        "    return static_cast<std::uint16_t>((r >> 3) << 11 | (g >> 2) << 5 | b >> 3);",
        "  }",
        "};",
        "",
        "namespace color {",
    ]
    for name, c in tokens["color"].items():
        r, g, b = rgb(c["value"])
        lines.append(f"inline constexpr Rgb {ident(name)}{{0x{r:02x}, 0x{g:02x}, 0x{b:02x}}};")
    lines += ["}  // namespace color", "", "// Roles on the console screen.", "namespace console {"]
    for role, name in tokens["theme"]["console"].items():
        lines.append(f"inline constexpr Rgb {ident(role)} = color::{ident(name)};")
    lines += ["}  // namespace console", "", "}  // namespace chilichip", ""]
    return "\n".join(lines)


def palette_md(tokens):
    out = []
    for source, title in SOURCES.items():
        out += [f"### {title}", "", '<div class="cc-swatches">']
        for name, c in tokens["color"].items():
            if c["source"] != source:
                continue
            r, g, b = rgb(c["value"])
            out.append(
                f'<div class="cc-swatch"><span class="cc-swatch__chip" style="background:{c["value"]}"></span>'
                f'<strong>{name}</strong><code>{c["value"]}</code><code>rgb({r} {g} {b})</code>'
                f'<code>--cc-{name}</code><small>{c["use"]}</small></div>'
            )
        out += ["</div>", ""]
    return "\n".join(out)


def roles_md(tokens):
    dark, light = tokens["theme"]["dark"], tokens["theme"]["light"]
    chip = lambda name: f'<span class="cc-dot" style="background:{tokens["color"][name]["value"]}"></span> `{name}`'
    out = ["| Role | Variable | Dark | Light |", "| --- | --- | --- | --- |"]
    out += [f"| {role} | `--cc-{role}` | {chip(dark[role])} | {chip(light[role])} |" for role in dark]
    return "\n".join(out) + "\n"


def contrast_md(tokens):
    out = ["| Theme | Text role | On `bg` | On `surface` | AA text (4.5:1) |", "| --- | --- | --- | --- | --- |"]
    for theme in tokens["theme"]:
        colours = resolved(tokens, theme)
        for role in TEXT_ROLES:
            if role not in colours:
                continue
            on_bg, on_surface = contrast(colours[role], colours["bg"]), contrast(colours[role], colours["surface"])
            ok = "Pass" if min(on_bg, on_surface) >= 4.5 else "Large text only"
            out.append(f"| {theme} | {role} | {on_bg}:1 | {on_surface}:1 | {ok} |")
        out.append(f"| {theme} | on-accent on accent | {contrast(colours['on-accent'], colours['accent'])}:1 | | Pass |")
    return "\n".join(out) + "\n"


def console_md(tokens):
    out = ["| Role | Colour | Hex | RGB565 | C++ |", "| --- | --- | --- | --- | --- |"]
    for role, name in tokens["theme"]["console"].items():
        value = tokens["color"][name]["value"]
        out.append(
            f'| {role} | <span class="cc-dot" style="background:{value}"></span> {name} | `{value}` '
            f"| `0x{rgb565(value):04X}` | `chilichip::console::{role.replace('-', '_')}` |"
        )
    return "\n".join(out) + "\n"


def outputs(tokens):
    """Every generated file and its content."""
    return {
        OUT / "chilichip.css": css(tokens).encode(),
        OUT / "chilichip.json": flat_json(tokens).encode(),
        OUT / "chilichip.hpp": hpp(tokens).encode(),
        ROOT / "docs" / "assets" / "chilichip-logo.svg": (ROOT / "logo" / "chilichip-logo.svg").read_bytes(),
        SNIPPETS / "palette.md": palette_md(tokens).encode(),
        SNIPPETS / "roles.md": roles_md(tokens).encode(),
        SNIPPETS / "contrast.md": contrast_md(tokens).encode(),
        SNIPPETS / "console.md": console_md(tokens).encode(),
    }


if __name__ == "__main__":
    for path, content in outputs(load()).items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content)
        print(f"wrote {path.relative_to(ROOT)}")
